from __future__ import annotations

from typing import Any, Protocol


class NumericsPolicy(Protocol):
    name: str

    def initialize(self, core: Any) -> None: ...
    def apply_surface_flux_defaults(self, core: Any, s_i: slice, s_j: slice, *, generation_fast_path: bool = False) -> None: ...
    def apply_pre_step_filters(self, core: Any) -> None: ...
    def apply_post_tracer_filters(self, core: Any) -> None: ...
    def advect_tracers(self, core: Any) -> None: ...
    def refresh_tracer_ghosts(self, core: Any, *, generation_fast_path: bool = False) -> None: ...
    def filter_tracers(self, core: Any, t_field: Any, s_field: Any, *, generation_fast_path: bool = False) -> tuple[Any, Any]: ...
    def filter_internal_velocity(self, core: Any, u_field: Any, v_field: Any, *, generation_fast_path: bool = False) -> tuple[Any, Any]: ...
    def eta_solver_options(self, core: Any) -> dict[str, object]: ...
