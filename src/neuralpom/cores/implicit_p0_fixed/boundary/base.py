from __future__ import annotations

from typing import Any, Protocol


class BoundaryPolicy(Protocol):
    name: str

    def apply_scalar2d(self, core: Any, field): ...
    def apply_velocity2d(self, core: Any, u_field, v_field): ...
    def apply_scalar3d(self, core: Any, field): ...
    def apply_velocity3d(self, core: Any, u_field, v_field): ...
    def apply_tracers(self, core: Any): ...
    def apply_flux2d(self, core: Any, xflux, yflux): ...
    def apply_flux3d(self, core: Any, xflux, yflux, k_slice): ...
    def apply_bcond(self, core: Any, idx: int, elf, uaf, vaf, uf, vf, w): ...
    def refresh_tracer_backups_after_apply(self) -> bool: ...
    def enforce_eta(self, core: Any, eta) -> None: ...
    def prepare_eta_rhs(self, core: Any, rhs) -> None: ...
